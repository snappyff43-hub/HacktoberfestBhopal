"""Gemini API integration service for CreatorFlow AI.

Acts as an AI script editor and review specialist to refine, polish,
and enhance scripts generated by local Gemma 4.
"""

import json
import logging
import re
import time
from typing import Any, Dict, Optional
import httpx
from app.core.config import GEMINI_API_KEY, GEMINI_MODEL
from app.schemas.project import GeneratedContentSchema, SceneItem

logger = logging.getLogger("creatorflow.gemini")


class GeminiService:
    """Service wrapping Google Gemini Generative Language REST API."""

    def __init__(self, api_key: str = GEMINI_API_KEY, default_model: str = GEMINI_MODEL):
        self.api_key = api_key
        # Default to gemini-flash-lite-latest for low latency (<2s) or user specified model
        self.default_model = default_model if default_model else "gemini-flash-lite-latest"

    def is_configured(self) -> bool:
        return bool(self.api_key and len(self.api_key) > 5)

    async def verify_auth(self) -> Dict[str, Any]:
        """Check API key validity by querying Gemini models catalog."""
        if not self.is_configured():
            return {
                "configured": False,
                "authenticated": False,
                "message": "GEMINI_API_KEY is not set in backend environment.",
            }

        url = f"https://generativelanguage.googleapis.com/v1beta/models?key={self.api_key}"
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.get(url)
            if res.status_code == 200:
                data = res.json()
                models = [m.get("name", "") for m in data.get("models", []) if "gemini" in m.get("name", "")]
                return {
                    "configured": True,
                    "authenticated": True,
                    "model_count": len(models),
                    "active_model": self.default_model,
                    "message": f"Gemini API authenticated. {len(models)} models available.",
                }
            else:
                return {
                    "configured": True,
                    "authenticated": False,
                    "message": f"Gemini authentication failed (HTTP {res.status_code}): {res.text[:100]}",
                }
        except Exception as e:
            return {
                "configured": True,
                "authenticated": False,
                "message": f"Error connecting to Gemini API: {str(e)}",
            }

    async def improve_script(
        self,
        base_script: GeneratedContentSchema,
        instructions: Optional[str] = "Make it punchier, improve retention and avatar delivery pacing",
    ) -> GeneratedContentSchema:
        """Send Gemma-generated script to Gemini for polish and enhancement."""
        if not self.is_configured():
            raise RuntimeError("Gemini API key is not configured in backend environment.")

        # Candidate models to try in order of latency and availability
        candidate_models = ["gemini-flash-lite-latest", "gemini-2.5-flash-lite", self.default_model]
        candidate_models = list(dict.fromkeys([m for m in candidate_models if m]))

        prompt = f"""You are an elite creative director and YouTube/Reels script doctor reviewing a video script draft generated by Gemma.
Your job is to elevate the script for an AI avatar video.

ORIGINAL DRAFT (by Gemma):
- Title: {base_script.title}
- Hook: {base_script.hook}
- Language: {base_script.language}
- Full Script: {base_script.script}
- Caption: {base_script.caption}
- Hashtags: {base_script.hashtags}
- Call to Action: {base_script.call_to_action}

USER IMPROVEMENT GOAL:
{instructions}

CRITICAL RULES:
1. Maintain the target language ({base_script.language}). If Hindi, use natural Devanagari Hindi. If Hinglish, conversational Hinglish. If English, crisp English.
2. Sharpen the hook to be irresistible within the first 3 seconds.
3. Make spoken narration flow effortlessly for an AI avatar voice (natural pauses, conversational rhythm).
4. Return ONLY a valid JSON object matching the exact schema below, with no markdown code blocks and no preamble.

REQUIRED JSON STRUCTURE:
{{
  "title": "Sharper, more compelling title",
  "hook": "Upgraded irresistible hook",
  "script": "Elevated spoken narration for the avatar",
  "language": "{base_script.language}",
  "scenes": [
    {{"scene_number": 1, "description": "Visual direction 1", "narration": "Spoken line 1"}},
    {{"scene_number": 2, "description": "Visual direction 2", "narration": "Spoken line 2"}},
    {{"scene_number": 3, "description": "Visual direction 3", "narration": "Spoken line 3"}}
  ],
  "caption": "Polished social post caption",
  "hashtags": ["3-5", "curated", "hashtags"],
  "description": "Engaging description with key takeaways",
  "call_to_action": "High-conversion CTA"
}}
"""

        payload = {
            "contents": [
                {
                    "parts": [
                        {"text": prompt}
                    ]
                }
            ],
            "generationConfig": {
                "temperature": 0.4,
                "maxOutputTokens": 1000,
            }
        }

        last_error = None
        for model in candidate_models:
            gen_url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={self.api_key}"
            try:
                async with httpx.AsyncClient(timeout=25.0) as client:
                    res = await client.post(gen_url, json=payload)
                if res.status_code == 200:
                    res_data = res.json()
                    candidates = res_data.get("candidates", [])
                    if candidates:
                        raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                        clean_text = raw_text.strip()
                        match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", clean_text)
                        if match:
                            clean_text = match.group(1).strip()
                        parsed = json.loads(clean_text)
                        return GeneratedContentSchema(**parsed)
                else:
                    last_error = f"Model {model} returned HTTP {res.status_code}: {res.text[:120]}"
            except Exception as e:
                last_error = f"Model {model} exception: {str(e)}"
                continue

        raise RuntimeError(f"Gemini script improvement failed across candidates: {last_error}")


gemini_service = GeminiService()
